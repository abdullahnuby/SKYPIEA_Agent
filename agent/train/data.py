PREFIXES = ("", "ممكن ", "لو سمحت ", "عايز ", "يا زكي ", "ممكن لو سمحت ")
SUFFIXES = ("", " ؟", " دلوقتي", " بسرعة")


def dataset(with_generated: bool = True) -> list[tuple[str, str]]:
    """(نص، تصنيف) — أوامر يدوية + كوربوس مولّد + تضخيم صيغ، بدون تكرار."""
    rows: list[tuple[str, str]] = []
    for label, phrases in PHRASES.items():
        for phrase in phrases:
            for p_index, prefix in enumerate(PREFIXES):
                for s_index, suffix in enumerate(SUFFIXES):
                    # مش كل تركيبة، عشان مانغرقش الموديل بتكرار
                    if p_index and s_index and (p_index + s_index) % 3 == 0:
                        continue
                    rows.append((f"{prefix}{phrase}{suffix}".strip(), label))

    if with_generated:
        rows.extend(generate_corpus())

    seen: set[str] = set()
    unique: list[tuple[str, str]] = []
    for text, label in rows:
        key = normalize(text, lower=True)
        if key in seen:
            continue
        seen.add(key)
        unique.append((text, label))
    return unique


def conflicts() -> list[tuple[str, str, str]]:
    """أي نص اتكرر بتصنيفين مختلفين — لازم يبقى صفر."""
    first: dict[str, str] = {}
    clashes: list[tuple[str, str, str]] = []
    for text, label in dataset():
        key = normalize(text, lower=True)
        if key in first and first[key] != label:
            clashes.append((text, first[key], label))
        else:
            first.setdefault(key, label)
    return clashes


def labels() -> list[str]:
    return sorted(PHRASES)
