PREFIXES = ("", "ممكن ", "لو سمحت ", "عايز ", "عاوز ", "يا زكي ", "ممكن لو سمحت ")
SUFFIXES = ("", " ؟", " دلوقتي", " بسرعة", " حالا")


def _variants(base: str, rng: random.Random) -> list[str]:
    """تنويع طبيعي: بادئة/لاحقة مختلفة مع الحفاظ على الجملة."""
    out = [base]
    for _ in range(3):
        prefix = rng.choice(PREFIXES)
        suffix = rng.choice(SUFFIXES)
        out.append(f"{prefix}{base}{suffix}".strip())
    return out


def generate(per_label: int = 80, seed: int = 11) -> list[tuple[str, str]]:
    """يولّد كوربوس متوازن: ~{per_label} صياغة لكل نية.

    بنلف على القوالب بالتساوي (round-robin) عشان كل قالب ياخد تمثيل،
    مش قالب واحد ياخد كل الحصة.
    """
    rng = random.Random(seed)
    rows: list[tuple[str, str]] = []

    tasks = {label: items for label, items in TEMPLATES.items()}
    tasks["unknown"] = UNKNOWN_SENTENCES

    for label, items in tasks.items():
        slots = SLOTS.get(label)
        bases: list[str] = []
        variants: list[str] = []
        for item in items:
            if "{x}" in item:
                for value in slots or []:
                    base = item.format(x=value)
                    bases.append(base)
                    variants.extend(_variants(base, rng)[1:])
            else:
                bases.append(item)
                variants.extend(_variants(item, rng)[1:])

        rng.shuffle(bases)
        rng.shuffle(variants)
        picked = list(dict.fromkeys(bases))
        if len(picked) < per_label:
            picked.extend(dict.fromkeys(variants))
        picked = picked[:per_label]

        rows.extend((text, label) for text in picked)

    rng.shuffle(rows)
    return rows


def stats() -> dict[str, int]:
    rows = generate()
    counts: dict[str, int] = {}
    for _, label in rows:
        counts[label] = counts.get(label, 0) + 1
    return counts
